"""
PCG-USD材质系统配置
包含配置结构定义和默认配置值
"""

from dataclasses import dataclass, field
import os
from typing import Dict, List, Optional, Union, Any
from pathlib import Path


@dataclass
class MaterialConfig:
    """材质配置"""
    roughness: float = 0.2
    metallic: float = 0.1
    opacity: float = 1.0
    emission_intensity: float = 0.0
    normal_intensity: float = 1.0
    
    # 贴图路径
    albedo_texture: Optional[str] = None
    roughness_texture: Optional[str] = None
    metallic_texture: Optional[str] = None
    normal_texture: Optional[str] = None
    noise_texture: Optional[str] = None
    
    # 混合参数
    noise_intensity: float = 0.2
    mix_factor: float = 0.5


@dataclass  
class PCGConfig:
    """PCG算法配置"""
    algorithm_type: str = "uniform"  # uniform, normal, grid, random
    variant_count: int = 10
    quality_levels: List[str] = field(default_factory=lambda: ["low", "medium", "high"])
    theme_styles: List[str] = field(default_factory=lambda: ["metallic", "concrete", "wood", "fabric"])
    
    # 参数分布配置
    roughness_range: tuple = (0.1, 0.8)
    metallic_range: tuple = (0.0, 1.0)
    noise_intensity_range: tuple = (0.1, 0.5)
    
    # 缓存配置
    enable_cache: bool = True
    cache_expiry_hours: int = 24
    max_cache_size_mb: int = 500


@dataclass
class USDConfig:
    """USD配置"""
