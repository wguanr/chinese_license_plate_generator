@dataclass
class LoggingConfig:
    """日志配置"""
    level: str = "INFO"
    format: str = "%(asctime)s - %(name)s - %(levelname)s - %(message)s"
    enable_file_logging: bool = True
    log_file: str = "pcg_materials.log"
    max_file_size_mb: int = 10
    backup_count: int = 5


@dataclass
class ConfigSchema:
    """完整的配置模式"""
    material: MaterialConfig = field(default_factory=MaterialConfig)
    pcg: PCGConfig = field(default_factory=PCGConfig)
    usd: USDConfig = field(default_factory=USDConfig)
    paths: PathConfig = field(default_factory=PathConfig)
    texture_classification: TextureClassificationConfig = field(default_factory=TextureClassificationConfig)
    logging: LoggingConfig = field(default_factory=LoggingConfig)
    
    # 系统配置
    version: str = "2.0.0"
    debug_mode: bool = False
    parallel_processing: bool = True
    max_workers: int = 4
    
    @classmethod
    def load_from_dict(cls, config_dict: Dict[str, Any]) -> 'ConfigSchema':
        """从字典加载配置"""
        return cls(
            material=MaterialConfig(**config_dict.get('material', {})),
            pcg=PCGConfig(**config_dict.get('pcg', {})),
            usd=USDConfig(**config_dict.get('usd', {})),
            paths=PathConfig(**config_dict.get('paths', {})),
            texture_classification=TextureClassificationConfig(**config_dict.get('texture_classification', {})),
            logging=LoggingConfig(**config_dict.get('logging', {})),
            version=config_dict.get('version', '2.0.0'),
            debug_mode=config_dict.get('debug_mode', False),
            parallel_processing=config_dict.get('parallel_processing', True),
            max_workers=config_dict.get('max_workers', 4)
        )
    
    def to_dict(self) -> Dict[str, Any]:
        """转换为字典"""
        from dataclasses import asdict
        return asdict(self)
    
    def validate(self) -> bool:
        """验证配置"""
        try:
            # 验证路径配置
            if not self.paths.output_dir_path:
                raise ValueError("输出目录不能为空")
            
            # 验证PCG配置
            if self.pcg.variant_count <= 0:
                raise ValueError("变体数量必须大于0")
                
            # 验证材质配置
            if not (0.0 <= self.material.roughness <= 1.0):
                raise ValueError("粗糙度必须在0-1范围内")
                
            if not (0.0 <= self.material.metallic <= 1.0):
                raise ValueError("金属度必须在0-1范围内")
            
            return True
            
        except Exception as e:
            print(f"❌ 配置验证失败: {e}")
            return False


